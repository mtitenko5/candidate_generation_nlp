def retrieve(qtexts):
    bm_ids = []
    bm_scores = []
    dense_ids = []
    dense_scores = []

    for start in tqdm(range(0, len(qtexts), Q_BATCH), desc="Retrieval"):
        end = min(start + Q_BATCH, len(qtexts))
        qt = qtexts[start:end]

        # BM25
        q = vectorizer.transform(qt).tocsr().astype(np.float32)
        q_scores = q @ bm25.T

        bi = np.empty((len(qt), TOP), np.int32)
        bs = np.empty((len(qt), TOP), np.float32)

        for i in range(len(qt)):
            s = q_scores[i].toarray().ravel()
            ix = np.argpartition(s, -TOP)[-TOP:]
            ix = ix[np.argsort(s[ix])[::-1]]
            bi[i] = ix
            bs[i] = s[ix]

        # Dense
        qe = model.encode(qt, batch_size=EMB_BATCH, normalize_embeddings=True,
                          convert_to_numpy=True).astype(np.float32)

        di = np.full((len(qt), TOP), -1, np.int32)
        ds = np.full((len(qt), TOP), -np.inf, np.float32)

        for st in range(0, len(item_emb), ITEM_CHUNK):
            en = min(st + ITEM_CHUNK, len(item_emb))

            s = qe @ item_emb[st:en].T
            ix = np.argpartition(s, -TOP, axis=1)[:, -TOP:]
            ss = np.take_along_axis(s, ix, axis=1)

            order = np.argsort(ss, axis=1)[:, ::-1]
            ix = np.take_along_axis(ix, order, axis=1) + st
            ss = np.take_along_axis(ss, order, axis=1)

            all_i = np.concatenate([di, ix], axis=1)
            all_s = np.concatenate([ds, ss], axis=1)

            take = np.argpartition(all_s, -TOP, axis=1)[:, -TOP:]
            di = np.take_along_axis(all_i, take, axis=1)
            ds = np.take_along_axis(all_s, take, axis=1)

            order = np.argsort(ds, axis=1)[:, ::-1]
            di = np.take_along_axis(di, order, axis=1)
            ds = np.take_along_axis(ds, order, axis=1)

            del s, ix, ss, all_i, all_s, take, order

        bm_ids.extend(bi)
        bm_scores.extend(bs)
        dense_ids.extend(di)
        dense_scores.extend(ds)

        del q, q_scores, qe, bi, bs, di, ds
        gc.collect()

    return bm_ids, bm_scores, dense_ids, dense_scores

